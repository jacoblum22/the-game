"""Build appendix/open-empirical-questions.md from every chapter's OEQ table rows (`| OEQ-CC-N | ... |`).
Each OEQ is a question the rules answer with a concrete shipped default, plus the named test that would
confirm or revise it. Re-run after any chapter edit: python rules/_process/build-oeq-appendix.py"""
import glob, os, re
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["# Open empirical questions", "",
       "Every rule in this ruleset ships with a concrete default. These are the defaults that rest on design",
       "judgment or simulation rather than play data. Each names the test that would confirm or revise it. They are",
       "the playtest agenda for the built game. Generated by `_process/build-oeq-appendix.py` from each",
       "chapter's *Open empirical questions* section, so edit the chapter, not this file.", ""]
total = 0; rows_by = []
for f in sorted(glob.glob(os.path.join(R, "[0-9][0-9]-*.md"))):
    title = open(f, encoding="utf-8").readline().lstrip("# ").strip()
    rows = [l for l in open(f, encoding="utf-8").read().split("\n") if re.match(r"^\| OEQ-\d\d-\d+", l)]
    if rows: rows_by.append((os.path.basename(f), title, rows)); total += len(rows)
out += ["**%d questions across %d chapters.** Chapter 13's are for the optional example setting." % (total, len(rows_by)), ""]
for fn, title, rows in rows_by:
    out += ["## %s (`%s`)" % (title, fn), "", "| Id | Question | Default shipped | Named test |", "|---|---|---|---|"] + rows + [""]
open(os.path.join(R, "appendix", "open-empirical-questions.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("wrote appendix/open-empirical-questions.md:", total, "questions")
